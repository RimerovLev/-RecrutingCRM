// ── Helper: resolve dotted key path ──────────────────────────────────────────
function resolve(obj, path) {
  return path.split('.').reduce((acc, k) => (acc && acc[k] !== undefined ? acc[k] : null), obj);
}

// ── translate(lang, key, fallback) ───────────────────────────────────────────
export function translate(lang, key, fallback) {
  const dict = translations[lang] || translations.ru;
  const val  = resolve(dict, key);
  if (val !== null) return val;
  // fallback to russian
  const ru = resolve(translations.ru, key);
  return ru !== null ? ru : (fallback ?? key);
}

